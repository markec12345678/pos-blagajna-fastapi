const DICTS: Record<string, LangDict> = { sl: SL, en: EN }

export type Lang = 'sl' | 'en'

export const LangContext = createContext<Lang>('sl')

export const useTranslation = () => {
  const lang = useContext(LangContext)
  const t = (key: string): string => DICTS[lang]?.[key] || DICTS['en']?.[key] || key
  return { t, lang }
}

export const getCurrentLang = (): string => {
  try { return localStorage.getItem('pos-lang') || 'sl' } catch { return 'sl' }
}

export const getItemName = (item: any, fallback: string): string => {
  if (!item?.translations) return fallback
  let trans: any
  try { trans = typeof item.translations === 'string' ? JSON.parse(item.translations) : item.translations } catch { return fallback }
  const l = getCurrentLang()
  if (trans[l]?.name) return trans[l].name
  if (trans['en']?.name) return trans['en'].name
  return fallback
}

export const getItemDesc = (item: any, fallback: string): string => {
  if (!item?.translations) return fallback
  let trans: any
  try { trans = typeof item.translations === 'string' ? JSON.parse(item.translations) : item.translations } catch { return fallback }
  const l = getCurrentLang()
  if (trans[l]?.description) return trans[l].description
  if (trans['en']?.description) return trans['en'].description
  return fallback
}
